"""Real registration API handler against an isolated PostgreSQL schema.

No live DB, no FastAPI startup/migrations, no mocked registration function.
This test verifies free allocation starts at 1000 in disposable staging.
"""
import os
import unittest
import uuid
from unittest.mock import patch

try:
    import psycopg
    from psycopg import sql
    from fastapi import HTTPException
    from api import UserData, register
except ImportError:
    psycopg = None

from staging_db_preflight import assert_disposable_staging_url


@unittest.skipUnless(os.getenv("RKU_VIP_TEST_DATABASE_URL") and psycopg,
                     "Isolated PostgreSQL test dependencies unavailable")
class ActualRegistrationApiStagingTests(unittest.TestCase):
    def test_real_registration_and_duplicate_email(self):
        url = os.environ["RKU_VIP_TEST_DATABASE_URL"]
        assert_disposable_staging_url(url)
        schema = "rku_api_" + uuid.uuid4().hex
        with psycopg.connect(url) as conn:
            if not conn.info.dbname.endswith("_vip_test"):
                self.fail("Refusing non-test database")
            conn.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
            conn.execute(sql.SQL(
                "CREATE TABLE {}.users (rku_id BIGINT GENERATED BY DEFAULT AS IDENTITY "
                "(START WITH 1) PRIMARY KEY, email TEXT UNIQUE NOT NULL, "
                "password_hash TEXT NOT NULL)"
            ).format(sql.Identifier(schema)))
        def isolated_connection():
            assert_disposable_staging_url(url)
            conn = psycopg.connect(url)
            conn.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            return conn
        try:
            with patch("registration.get_connection", side_effect=isolated_connection):
                result = register(UserData(email="new@example.com",
                                           password="staging-test-password-123"))
                self.assertEqual(result["rku_id"], 1000)
                self.assertEqual(result["email"], "new@example.com")
                with self.assertRaises(HTTPException) as error:
                    register(UserData(email="new@example.com",
                                      password="staging-test-password-123"))
                self.assertEqual(error.exception.status_code, 409)
            with isolated_connection() as conn:
                rows = conn.execute("SELECT rku_id, email FROM users").fetchall()
                self.assertEqual(rows, [(1000, "new@example.com")])
        finally:
            with psycopg.connect(url) as conn:
                conn.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(
                    sql.Identifier(schema)))


if __name__ == "__main__":
    unittest.main()
