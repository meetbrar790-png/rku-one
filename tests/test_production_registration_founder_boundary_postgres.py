"""Regression: actual registration preserves founder and VIP range in disposable PostgreSQL.

Never connects to the production database.
"""
import os
import unittest
import uuid
from unittest.mock import patch

try:
    import psycopg
    from psycopg import sql
    from registration import register_user
except ImportError:
    psycopg = None
    sql = None
    register_user = None

from staging_db_preflight import assert_disposable_staging_url


@unittest.skipUnless(os.getenv("RKU_VIP_TEST_DATABASE_URL") and psycopg,
                     "Disposable PostgreSQL test database unavailable")
class ProductionRegistrationBoundaryTests(unittest.TestCase):
    def test_existing_founder_unchanged_and_free_ids_start_at_1001(self):
        url = os.environ["RKU_VIP_TEST_DATABASE_URL"]
        assert_disposable_staging_url(url)
        schema = "rku_boundary_" + uuid.uuid4().hex
        with psycopg.connect(url) as conn:
            conn.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
            conn.execute(sql.SQL(
                "CREATE TABLE {}.users (rku_id BIGINT GENERATED BY DEFAULT AS IDENTITY "
                "(START WITH 1) PRIMARY KEY, email TEXT UNIQUE NOT NULL, "
                "password_hash TEXT NOT NULL)"
            ).format(sql.Identifier(schema)))
            conn.execute(sql.SQL(
                "INSERT INTO {}.users (rku_id, email, password_hash) VALUES (1, %s, %s)"
            ).format(sql.Identifier(schema)), ("founder@example.com", "existing-hash"))

        def isolated_connection():
            assert_disposable_staging_url(url)
            conn = psycopg.connect(url)
            conn.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            return conn

        try:
            with patch("registration.get_connection", side_effect=isolated_connection):
                first = register_user("FIRST@example.com", "long-test-password-123")
                second = register_user("second@example.com", "long-test-password-456")
            self.assertEqual(first["rku_id"], 1001)
            self.assertEqual(second["rku_id"], 1002)
            with isolated_connection() as conn:
                rows = conn.execute(
                    "SELECT rku_id, email, password_hash FROM users ORDER BY rku_id"
                ).fetchall()
            self.assertEqual([r[0] for r in rows], [1, 1001, 1002])
            self.assertEqual(rows[0], (1, "founder@example.com", "existing-hash"))
            self.assertEqual(rows[1][1], "first@example.com")
            self.assertEqual(rows[2][1], "second@example.com")
        finally:
            with psycopg.connect(url) as conn:
                conn.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(
                    sql.Identifier(schema)))


if __name__ == "__main__":
    unittest.main()
