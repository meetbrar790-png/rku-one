import os
import psycopg
from pwdlib import PasswordHash
from vip_tier_policy import FREE_ID_START
from vip_allocator_prototype import ALLOCATION_LOCK_KEY

password_hash = PasswordHash.recommended()

def get_connection():
    database_url = os.environ["DATABASE_URL"]
    return psycopg.connect(database_url)

def setup_database():
    with get_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                rku_id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    (START WITH 1) PRIMARY KEY,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)
        conn.execute("""CREATE TABLE IF NOT EXISTS login_failures (
            email TEXT PRIMARY KEY,
            failures INTEGER NOT NULL DEFAULT 0,
            first_failure TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            blocked_until TIMESTAMPTZ
        )""")
        conn.execute("DELETE FROM login_failures WHERE blocked_until IS NULL AND first_failure < NOW() - INTERVAL '1 day'")
        # Preserve issued IDs without an exclusive table lock at startup.
        # A fresh identity sequence already starts at 1 by schema definition.

def register_user(email, password):
    if not isinstance(email, str) or not isinstance(password, str):
        raise ValueError("Valid email and password of 12 to 256 characters required")
    email = email.strip().lower()

    if not email or len(email) > 254 or not 12 <= len(password) <= 256:
        raise ValueError("Valid email and password of 12 to 256 characters required")

    hashed = password_hash.hash(password)

    with get_connection() as conn:
        # Shared transaction lock: all future VIP allocation paths must use it.
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (ALLOCATION_LOCK_KEY,))
        # Existing IDs remain unchanged. Never reset the live sequence.
        # Consume pre-1000 sequence values without assigning them.
        sequence_name = conn.execute(
            "SELECT pg_get_serial_sequence('users', 'rku_id')"
        ).fetchone()[0]
        if not sequence_name:
            raise RuntimeError("RKU ID identity sequence missing")
        result = None
        for _ in range(10000):
            candidate = conn.execute(
                "SELECT nextval(%s::regclass)", (sequence_name,)
            ).fetchone()[0]
            if candidate < FREE_ID_START:
                continue
            occupied = conn.execute(
                "SELECT EXISTS(SELECT 1 FROM users WHERE rku_id=%s)",
                (candidate,),
            ).fetchone()[0]
            if occupied:
                continue
            result = conn.execute(
                "INSERT INTO users (rku_id, email, password_hash) "
                "VALUES (%s, %s, %s) RETURNING rku_id",
                (candidate, email, hashed),
            ).fetchone()
            break
        if result is None:
            raise RuntimeError("Free RKU ID allocation exhausted review limit")

    return {"rku_id": result[0], "email": email}

def verify_login(email, password):
    if not isinstance(email, str) or not isinstance(password, str) or len(password) > 256 or len(email) > 254:
        return None
    normalized_email = email.strip().lower()
    if not normalized_email:
        return None
    with get_connection() as conn:
        # Serialize login checks for each email across server workers.
        conn.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))", (normalized_email,))
        state = conn.execute(
            "SELECT failures, blocked_until > NOW() FROM login_failures WHERE email=%s",
            (normalized_email,)
        ).fetchone()
        if state and state[1]:
            return None
        user = conn.execute(
            "SELECT rku_id, password_hash FROM users WHERE email=%s",
            (normalized_email,)
        ).fetchone()
        if user and password_hash.verify(password, user[1]):
            conn.execute("DELETE FROM login_failures WHERE email=%s", (normalized_email,))
            return {"rku_id": user[0]}
        conn.execute("""
            INSERT INTO login_failures(email, failures, first_failure, blocked_until)
            VALUES (%s, 1, NOW(), NULL)
            ON CONFLICT (email) DO UPDATE SET
                failures = CASE
                    WHEN login_failures.first_failure < NOW() - INTERVAL '15 minutes' THEN 1
                    ELSE login_failures.failures + 1 END,
                first_failure = CASE
                    WHEN login_failures.first_failure < NOW() - INTERVAL '15 minutes' THEN NOW()
                    ELSE login_failures.first_failure END,
                blocked_until = CASE
                    WHEN login_failures.first_failure < NOW() - INTERVAL '15 minutes' THEN NULL
                    WHEN login_failures.failures + 1 >= 5 THEN NOW() + INTERVAL '15 minutes'
                    ELSE NULL END
        """, (normalized_email,))
    return None
