import os
import psycopg
from pwdlib import PasswordHash

password_hash = PasswordHash.recommended()

def get_connection():
    database_url = os.environ["DATABASE_URL"]
    return psycopg.connect(database_url)

def setup_database():
    with get_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                rku_id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    (START WITH 1) PRIMARY KEY,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)
        # Preserve every previously issued ID. Only change the sequence if
        # it has never been used and no accounts exist.
        conn.execute("LOCK TABLE users IN ACCESS EXCLUSIVE MODE")
        sequence_name = conn.execute(
            "SELECT pg_get_serial_sequence('users', 'rku_id')"
        ).fetchone()[0]
        if sequence_name:
            from psycopg import sql
            seq = sql.Identifier(*sequence_name.split("."))
            sequence_state = conn.execute(
                sql.SQL("SELECT last_value, is_called FROM {}").format(seq)
            ).fetchone()
            has_users = conn.execute(
                "SELECT EXISTS (SELECT 1 FROM users)"
            ).fetchone()[0]
            if not has_users and not sequence_state[1]:
                conn.execute(
                    "ALTER TABLE users ALTER COLUMN rku_id RESTART WITH 1"
                )

def register_user(email, password):
    email = email.strip().lower()

    if not email or len(email) > 254 or not 12 <= len(password) <= 256:
        raise ValueError("Valid email and password of 12 to 256 characters required")

    hashed = password_hash.hash(password)

    with get_connection() as conn:
        result = conn.execute(
            """
            INSERT INTO users (email, password_hash)
            VALUES (%s, %s)
            RETURNING rku_id
            """,
            (email, hashed)
        ).fetchone()

    return {"rku_id": result[0], "email": email}

def verify_login(email, password):
    if not isinstance(password, str) or len(password) > 256 or len(email) > 254:
        return None
    with get_connection() as conn:
        user = conn.execute(
            """
            SELECT rku_id, password_hash
            FROM users WHERE email = %s
            """,
            (email.strip().lower(),)
        ).fetchone()

    if user and password_hash.verify(password, user[1]):
        return {"rku_id": user[0]}

    return None
